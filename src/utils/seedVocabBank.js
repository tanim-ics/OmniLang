import mongoose from 'mongoose';
import { createHash } from 'crypto';
import { readFileSync, existsSync } from 'fs';
import { fileURLToPath } from 'url';
import { dirname, join } from 'path';
import VocabBank from '../models/VocabBank.js';
import Vocabulary from '../models/Vocabulary.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
export const BANK_DATA_PATH = join(__dirname, '../data/vocabBank15k.json');
const LEGACY_GLOSSES_PATH = join(__dirname, '../data/vocabBankLegacyGlosses.json');

const META_COLLECTION = 'appmeta';
const META_ID = 'vocabBank';

// Template sentences generated by the original bank build ("Hier ist das Ich.").
// Cards copied from the bank into user decks still carry them.
const TEMPLATE_EXAMPLE = new RegExp('^(Hier ist (der|die|das) |Ich habe (der|die|das) neuen? .* gestern gesehen\\.'
    + '|Wir müssen prüfen, ob |Ich möchte heute \\S+\\.$|Wir haben gestern beschlossen, zusammen zu '
    + '|Es ist ratsam, diese Angelegenheit |Das ist wirklich sehr \\S+\\.$|Das Ergebnis war überraschend '
    + '|Unter diesen Umständen scheint die Entscheidung |Sie spricht \\S+ mit ihren Kollegen\\.|Bitte verwende das Wort )');

/**
 * Refreshes deck cards that were copied from an older bank version (SRS progress is untouched):
 *  - cards whose example is a template sentence ("Hier ist das Ich."), and
 *  - cards whose translation is one an earlier bank shipped and has since corrected
 *    (src/data/vocabBankLegacyGlosses.json, e.g. "die Sängerin = songstress").
 * They get the current bank translation and example; when the word has left the bank,
 * only a template example is cleared.
 */
export async function refreshDeckCardsFromBank({ log = console.log } = {}) {
    const legacy = existsSync(LEGACY_GLOSSES_PATH) ? JSON.parse(readFileSync(LEGACY_GLOSSES_PATH, 'utf-8')) : {};
    const candidates = await Vocabulary.find({
        $or: [{ example: TEMPLATE_EXAMPLE }, { word: { $in: Object.keys(legacy) } }]
    }).select('word translation example').lean();
    const stale = candidates.filter(c => TEMPLATE_EXAMPLE.test(c.example || '')
        || (legacy[c.word] || []).includes(c.translation));
    if (!stale.length) return 0;

    const words = [...new Set(stale.map(c => c.word))];
    const bank = new Map((await VocabBank.find({ word: { $in: words } }).lean()).map(b => [b.word, b]));
    const ops = stale.map(card => {
        const b = bank.get(card.word);
        const templated = TEMPLATE_EXAMPLE.test(card.example || '');
        let $set;
        if (b) {
            $set = { translation: b.translation };
            if (templated || !card.example) {
                Object.assign($set, { example: b.example || '', sourceText: b.exampleEn || b.topic || 'Vocab Bank' });
            }
        } else {
            $set = templated ? { example: '', sourceText: '' } : {};
        }
        return { updateOne: { filter: { _id: card._id }, update: { $set } } };
    }).filter(op => Object.keys(op.updateOne.update.$set).length);
    if (!ops.length) return 0;
    await Vocabulary.bulkWrite(ops, { ordered: false });
    log(`✓ Refreshed ${ops.length} deck cards that still had outdated translations or template sentences`);
    return ops.length;
}

/**
 * Seeds the VocabBank collection from src/data/vocabBank15k.json.
 * The file's SHA-1 is stored as a version marker, so an edited data file
 * replaces the collection on the next start. `force` reseeds regardless.
 */
export async function seedVocabBank({ force = false, log = console.log } = {}) {
    if (!existsSync(BANK_DATA_PATH)) {
        log('⚠️ VocabBank data file missing, skipping seed');
        return { seeded: false };
    }
    const raw = readFileSync(BANK_DATA_PATH, 'utf-8');
    const version = createHash('sha1').update(raw).digest('hex');
    const meta = mongoose.connection.db.collection(META_COLLECTION);
    const current = await meta.findOne({ _id: META_ID });
    const count = await VocabBank.countDocuments();

    if (!force && current?.version === version && count > 0) {
        log(`✓ Vocabulary Bank ready in MongoDB (${count} words)`);
        return { seeded: false, count };
    }

    const words = JSON.parse(raw);
    log(`⏳ Seeding Vocabulary Bank into MongoDB (${words.length} words, replacing ${count})...`);
    await VocabBank.deleteMany({});
    const batchSize = 2500;
    for (let i = 0; i < words.length; i += batchSize) {
        await VocabBank.insertMany(words.slice(i, i + batchSize), { ordered: false });
    }
    const newCount = await VocabBank.countDocuments();
    await meta.updateOne(
        { _id: META_ID },
        { $set: { version, count: newCount, seededAt: new Date() } },
        { upsert: true }
    );
    log(`✓ Vocabulary Bank ready in MongoDB (${newCount} words, version ${version.slice(0, 8)})`);
    await refreshDeckCardsFromBank({ log });
    return { seeded: true, count: newCount };
}
